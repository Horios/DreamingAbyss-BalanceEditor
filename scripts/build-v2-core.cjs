/* Reuse the exact four existing model bodies. No alternate data model. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const names=['EmberwildSecondsSchema','EmberwildSkillSystem','EmberwildMechanisms','EmberwildBalanceDocument'];
function build(){
 const html=fs.readFileSync(path.join(root,'balance-editor.html'),'utf8'),blocks=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
 const parts=names.map(name=>{
  const matches=blocks.filter(m=>new RegExp('root\\.'+name+'\\s*=').test(m[2]));
  if(matches.length!==1)throw Error(name+' must have exactly one existing implementation');
  const m=matches[0];return {name,source:m[2],line:html.slice(0,m.index).split('\n').length,sha256:hash(m[2])};
 });
 const code='/* Generated by build-v2-core.cjs from the existing Dreaming Abyss editor. */\n'+parts.map(p=>'/* '+p.name+' */\n'+p.source).join('\n');
 return {code,provenance:{editorSha256:hash(html),bundleSha256:hash(code),models:parts.map(({source,...p})=>p)}};
}
if(require.main===module){const b=build();fs.writeFileSync(path.join(root,'scripts/v2-shared-core.js'),b.code);fs.writeFileSync(path.join(root,'docs/v2-core-provenance.json'),JSON.stringify(b.provenance,null,2)+'\n');console.log('Reused '+b.provenance.models.length+' existing model implementations');}
module.exports={build,names};
